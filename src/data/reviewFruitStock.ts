export type StockFilter = 'all' | 'stock' | 'A' | 'B'

export function filterAssociationStock(records: AssociationRecord[], filter: StockFilter) {
  if (filter === 'all') return records
  return records.filter((record) => filter === 'stock'
    ? record.sourceType === '復習ストック'
    : record.sourceType === '復習ストック' && record.priority === filter)
}
